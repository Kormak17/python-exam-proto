def check_answer(question, raw):

  true_ans = question['answer']
  tip = question['type']
  temp = raw.lower().strip()

  if temp == "":
    return 'нет ответа'
  
  if tip == 'один':
    if str(temp) == str(true_ans):
      return 'верно'
    else:
      return 'неверно'

  if tip == 'короткий':
    if '|' in true_ans:
      true_ans_lst = true_ans.split('|')
      if temp in true_ans_lst:
        return 'верно'
      else:
        return 'неверно'
    else:   
      if str(temp) == str(true_ans):
        return 'верно'
      else:
        return 'неверно'
  
  if tip == 'несколько':
    lst = []
    true_ans = true_ans.strip().split(',')
    sorted_true_ans = sorted(true_ans)
    ans = temp.split(',')
    for el in ans:
      lst.append(el.strip())
    sorted_ans = sorted(lst)
    if sorted_true_ans == sorted_ans:
      return 'верно'
    else:
      return 'неверно'


